#!/usr/bin/env bash
# Merge all modules into ONE submission file.
# Usage: scripts/merge.sh [STUDENT_ID]     -> build/<STUDENT_ID>.c
set -euo pipefail
cd "$(dirname "$0")/.."

ID="${1:-studentID}"
OUT="build/${ID}.c"
mkdir -p build

# Order matters: headers (declarations) first, then implementations, main last.
FILES=(
  src/bit_ops.h src/des_tables.h src/key_schedule.h src/des.h src/file_ecb.h
  src/des_tables.c src/key_schedule.c src/des.c src/file_ecb.c src/main.c
)

{
  cat docs/TEAM_HEADER.txt
  echo
  echo "/* Generated by scripts/merge.sh - edit the files in src/, not this file. */"
  for f in "${FILES[@]}"; do
    if [[ ! -s "$f" ]]; then
      echo "merge.sh: missing or empty $f" >&2; exit 1
    fi
    echo
    echo "/* ===================== $f ===================== */"
    # drop project-local includes; system includes (<...>) are kept
    grep -v '^[[:space:]]*#[[:space:]]*include[[:space:]]*"' "$f"
  done
} > "$OUT"

if grep -q '\[Full name\]' "$OUT"; then
  echo "merge.sh: WARNING - team names/IDs still placeholders in docs/TEAM_HEADER.txt" >&2
fi
echo "Wrote $OUT"
